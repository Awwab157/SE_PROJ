"""Generate docs/api.md from the live tool registry and pydantic schemas (SE-7).

Usage: ``python scripts/gen_api_docs.py`` (rewrites docs/api.md). CI does not regenerate it; re-run after
changing a tool, schema or the quota table.
"""

from __future__ import annotations

import json
import sys
import tempfile
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "src"))

import anyio  # noqa: E402
from mcp import Client  # noqa: E402

from yt_intel_mcp.approval import RecordingApprovalPrompt  # noqa: E402
from yt_intel_mcp.ids import ChannelRef  # noqa: E402
from yt_intel_mcp.schemas import RecommendFilters  # noqa: E402
from yt_intel_mcp.server import build_app, create_server  # noqa: E402
from yt_intel_mcp.services import engagement, playlist, recommendations, similar_channels, similar_videos  # noqa: E402

COMMON = [
    "invalid_input",
    "authorization_required",
    "reauthorization_required",
    "quota_budget_exceeded",
    "quota_exceeded",
    "rate_limited",
    "transient_error",
    "internal_error",
]
ERRORS = {
    "find_similar_videos": COMMON + ["not_found"],
    "find_similar_channels": COMMON + ["not_found"],
    "recommend_videos": COMMON,
    "analyze_engagement": COMMON,
    "propose_playlist": COMMON,
    "create_playlist": COMMON
    + [
        "proposal_not_found",
        "proposal_expired",
        "proposal_declined",
        "proposal_in_progress",
        "confirmation_invalid",
        "approval_unavailable",
        "write_scope_required",
        "youtube_signup_required",
        "forbidden",
    ],
    "start_authorization": ["authorization_required", "internal_error"],
    "revoke_authorization": ["internal_error"],
    "clear_cache": ["internal_error"],
}


def quota_costs(app) -> dict[str, str]:
    est = app.quota.estimate

    def fmt(plan) -> str:
        e = est(plan)
        return ", ".join(f"{k} {v}" for k, v in e.items() if v) or "0"

    sv_full, sv_min = similar_videos.plan(app)
    sc_full, sc_min = similar_channels.plan(app, ChannelRef("handle", "@x"))
    rv_full, rv_min = recommendations.plan(app)
    pp_full, pp_min = playlist.plan(app)
    return {
        "find_similar_videos": f"up to {fmt(sv_full)} (minimum {fmt(sv_min)})",
        "find_similar_channels": f"up to {fmt(sc_full)} (minimum {fmt(sc_min)}; /c/ URLs +1 search)",
        "recommend_videos": f"up to {fmt(rv_full)} (minimum {fmt(rv_min)})",
        "analyze_engagement": f"up to {fmt(engagement.plan(app))}",
        "propose_playlist": f"up to {fmt(pp_full)} (minimum {fmt(pp_min)})",
        "create_playlist": "units 50 (playlists.insert) + 50 per video (playlistItems.insert), reserved atomically",
        "start_authorization": "0",
        "revoke_authorization": "0",
        "clear_cache": "0",
    }


async def collect(app) -> tuple[list, list, list, list]:
    async with Client(create_server(app), mode="legacy") as client:
        tools = (await client.list_tools()).tools
        resources = (await client.list_resources()).resources
        templates = (await client.list_resource_templates()).resource_templates
        prompts = (await client.list_prompts()).prompts
    return tools, resources, templates, prompts


def main() -> int:
    with tempfile.TemporaryDirectory() as tmp:
        app = build_app(state_dir=Path(tmp), provider_mode="fixture", approval_prompt=RecordingApprovalPrompt())
        tools, resources, templates, prompts = anyio.run(collect, app)
        costs = quota_costs(app)
    lines = [
        "# API reference",
        "",
        "Generated by `scripts/gen_api_docs.py` from the registered MCP tools and pydantic models. Transport: stdio.",
        "",
        "Every successful result has `structuredContent` (matching the output schema) plus two text blocks: a",
        "short `summary` and the same data as JSON (UI-1). Errors are results with `isError: true` and",
        '`structuredContent = {"error": {"code", "cause", "next_step", "details"}}` (UI-3).',
        "",
        "Quota costs are upper bounds reserved before the first call; unused quota is released afterwards and",
        "cache hits cost nothing. Bucket limits and per-method costs are in `config/quota.yaml`.",
        "",
        "| Tool | Writes to YouTube | Quota (default config) |",
        "|---|---|---|",
    ]
    for t in tools:
        writes = "**YES**" if "Writes to YouTube: YES" in (t.description or "") else "no"
        lines.append(f"| `{t.name}` | {writes} | {costs[t.name]} |")
    lines.append("")
    for t in tools:
        input_schema = dict(t.input_schema)
        if t.name == "recommend_videos":
            input_schema.setdefault("$comment", "filters is validated against RecommendFilters (below)")
        lines += [
            f"## `{t.name}`",
            "",
            t.description or "",
            "",
            f"**Errors:** {', '.join(f'`{c}`' for c in ERRORS[t.name])}",
            "",
            f"**Quota:** {costs[t.name]}",
            "",
            "<details><summary>Input schema</summary>",
            "",
            "```json",
            json.dumps(input_schema, indent=2),
            "```",
            "</details>",
            "",
            "<details><summary>Output schema</summary>",
            "",
            "```json",
            json.dumps(t.output_schema, indent=2),
            "```",
            "</details>",
            "",
        ]
    lines += [
        "### `RecommendFilters` (the `filters` argument of `recommend_videos`)",
        "",
        "```json",
        json.dumps(RecommendFilters.model_json_schema(), indent=2),
        "```",
        "",
        "## Resources (read-only)",
        "",
        "| URI | Description |",
        "|---|---|",
    ]
    for r in resources:
        lines.append(f"| `{r.uri}` | {r.description} |")
    for r in templates:
        lines.append(f"| `{r.uri_template}` | {r.description} |")
    lines += [
        "",
        "Resources never contain tokens, client secrets, confirmation codes or code hashes.",
        "",
        "## Prompts (Agent Skills)",
        "",
        "Agent Skills are exposed as MCP prompts. The prompt text is the skill's `skills/<name>/SKILL.md` body;",
        "skills are not registered as tools or resources (FR-8.5).",
        "",
        "| Prompt | Arguments | Description |",
        "|---|---|---|",
    ]
    for pr in prompts:
        args = ", ".join(f"`{a.name}`" + (" (required)" if a.required else "") for a in pr.arguments or [])
        lines.append(f"| `{pr.name}` | {args} | {pr.description} |")
    lines += [
        "",
        "## Error codes",
        "",
        "| Code | Meaning |",
        "|---|---|",
    ]
    from yt_intel_mcp import errors as err_mod

    seen = set()
    for obj in vars(err_mod).values():
        if isinstance(obj, type) and issubclass(obj, err_mod.YTIntelError) and obj.code not in seen:
            seen.add(obj.code)
            lines.append(f"| `{obj.code}` | {obj.default_next_step} |")
    (ROOT / "docs" / "api.md").write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"wrote docs/api.md ({len(tools)} tools)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
